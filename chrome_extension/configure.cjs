const fs = require('node:fs')
const path = require('node:path')

function backendUrl(value) {
  const url = new URL(value)
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.search || url.hash || url.pathname !== '/') {
    throw new Error('API_BASE_URL must be an HTTP(S) origin without credentials, path, query or fragment.')
  }
  if (url.protocol === 'http:' && !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) {
    throw new Error('Remote backend URLs must use HTTPS.')
  }
  return url.origin
}

function configure(directory = __dirname, environment = process.env) {
  const envPath = path.join(directory, '.env')
  const lines = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8').split(/\r?\n/) : []
  const setting = lines.find(line => /^\s*API_BASE_URL\s*=/.test(line))
  const local = setting?.slice(setting.indexOf('=') + 1).trim().replace(/^(['"])(.*)\1$/, '$2')
  const origin = backendUrl(environment.API_BASE_URL?.trim() || local || 'https://applyr-backend.vercel.app')
  const manifestPath = path.join(directory, 'manifest.json')
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  // Chrome match patterns use the hostname, without a port.
  const url = new URL(origin)
  manifest.host_permissions = [`${url.protocol}//${url.hostname}/*`]
  fs.writeFileSync(path.join(directory, 'config.js'), `// Generated by configure.cjs. Only public configuration belongs here.\nglobalThis.APPLYR_API_URL = ${JSON.stringify(origin)};\n`)
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
  return origin
}

if (require.main === module) {
  try { console.log(`Extension backend: ${configure()}. Reload the extension in Chrome.`) }
  catch (error) { console.error(error.message); process.exitCode = 1 }
}
module.exports = { configure, backendUrl }
